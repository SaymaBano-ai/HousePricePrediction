import streamlit as st
import pandas as pd
import joblib
import os

BASE = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(BASE, "..", "Model", "best_house_price_model.pkl")
META_PATH = os.path.join(BASE, "..", "Model", "model_metadata.pkl")

st.set_page_config(page_title="House Price Predictor", page_icon="🏠", layout="centered")

@st.cache_resource
def load_model():
    model = joblib.load(MODEL_PATH)
    meta = joblib.load(META_PATH)
    return model, meta

model, meta = load_model()

st.title("🏠 House Price Prediction System")
st.caption(f"AIML Summer Internship 2026 Capstone Project | Model in use: **{meta['best_model_name']}**")
st.write("Enter the property details below to get an estimated market price.")

with st.form("prediction_form"):
    col1, col2 = st.columns(2)

    with col1:
        city = st.selectbox("City", ["Lucknow", "Prayagraj", "Kanpur", "Varanasi", "Noida", "Delhi", "Pune", "Bangalore"])
        property_type = st.selectbox("Property Type", ["Apartment", "Independent House", "Villa", "Builder Floor"])
        furnishing = st.selectbox("Furnishing", ["Unfurnished", "Semi-Furnished", "Fully-Furnished"])
        tier_rank = st.selectbox("Locality Tier", ["Affordable", "Mid-range", "Premium"])
        area_sqft = st.number_input("Area (Sq Ft)", min_value=200, max_value=10000, value=1200, step=50)
        bhk = st.slider("BHK", 1, 5, 2)
        bathrooms = st.slider("Bathrooms", 1, 5, 2)
        balconies = st.slider("Balconies", 0, 3, 1)

    with col2:
        age_years = st.slider("Property Age (Years)", 0, 35, 5)
        floor_no = st.number_input("Floor Number", min_value=0, max_value=40, value=3)
        total_floors = st.number_input("Total Floors in Building", min_value=1, max_value=45, value=10)
        parking = st.slider("Parking Spaces", 0, 3, 1)
        has_lift = st.checkbox("Lift Available", value=True)
        near_metro_km = st.number_input("Distance to Metro (KM)", min_value=0.0, max_value=30.0, value=3.0, step=0.5)
        school_nearby = st.checkbox("School Nearby", value=True)
        hospital_nearby = st.checkbox("Hospital Nearby", value=True)

    submitted = st.form_submit_button("Predict Price", use_container_width=True)

if submitted:
    tier_map = {"Affordable": 0, "Mid-range": 1, "Premium": 2}
    tier_code = tier_map[tier_rank]

    input_dict = {
        "City": city,
        "Property_Type": property_type,
        "Area_SqFt": area_sqft,
        "BHK": bhk,
        "Bathrooms": bathrooms,
        "Balconies": balconies,
        "Age_Years": age_years,
        "Furnishing": furnishing,
        "Floor_No": floor_no,
        "Total_Floors": total_floors,
        "Parking_Spaces": parking,
        "Has_Lift": int(has_lift),
        "Distance_to_Metro_KM": near_metro_km,
        "School_Nearby": int(school_nearby),
        "Hospital_Nearby": int(hospital_nearby),
        "Tier_Rank": tier_code,
        "Floor_Ratio": floor_no / max(total_floors, 1),
        "Rooms_per_Bathroom": bhk / max(bathrooms, 1),
        "Is_New_Property": int(age_years <= 2),
        "Amenity_Score": int(school_nearby) + int(hospital_nearby) + int(has_lift) + int(parking > 0),
    }

    input_df = pd.DataFrame([input_dict])
    prediction = model.predict(input_df)[0]

    st.success(f"### Estimated House Price: ₹ {prediction:,.0f}")
    st.metric("Price per Sq Ft", f"₹ {prediction/area_sqft:,.0f}")

    st.info(
        "This estimate is generated by a trained regression model "
        "based on historical property data and the features provided. "
        "Actual market prices may vary due to negotiation, exact micro-location, and market conditions."
    )

st.divider()
st.caption("Capstone Project — House Price Prediction System | IIHMF, MNNIT Allahabad")
